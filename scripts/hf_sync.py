# Usage: hf_sync.py [--summary <file>]
# Checks every public model, dataset and Space on Hugging Face under HF_USER and updates
# data/huggingface.csv (the pinned version of each) and huggingface.md (the readable list).
# The note column is filled in by hand and kept as is. Standard library only, no token needed.
import csv, json, os, sys, urllib.request, urllib.error

HF_USER = "pratikgx"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV_PATH = os.path.join(ROOT, "data", "huggingface.csv")
MD_PATH = os.path.join(ROOT, "huggingface.md")
FIELDS = ["type", "repo", "revision", "updated", "status", "note"]
KINDS = {"model": "models", "dataset": "datasets", "space": "spaces"}
URL_PREFIX = {"model": "", "dataset": "datasets/", "space": "spaces/"}

def get(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "hf-sync"}), timeout=60) as r:
        return json.load(r)

def hf_url(row, rev=None):
    url = f"https://huggingface.co/{URL_PREFIX[row['type']]}{row['repo']}"
    return f"{url}/tree/{rev}" if rev else url

def commits_since(kind, repo, old_rev):
    # Commit titles newer than old_rev, newest first, so the pull request says what changed
    try:
        commits = get(f"https://huggingface.co/api/{KINDS[kind]}/{repo}/commits/main")
    except urllib.error.HTTPError:
        return []
    out = []
    for c in commits:
        if c["id"] == old_rev: break
        out.append(f"{c['date'][:10]} {c['id'][:8]} {c['title']}")
    return out[:10]

def load_rows():
    if not os.path.exists(CSV_PATH): return {}
    with open(CSV_PATH, newline="") as f:
        return {(r["type"], r["repo"]): r for r in csv.DictReader(f)}

def write_md(rows):
    lines = [
        "# My Hugging Face uploads", "",
        "Everything I've put on Hugging Face, the note that explains it and the exact version this repo points to. "
        "A GitHub Action checks Hugging Face every night and opens a pull request when something changes.", "",
        "The list is generated from [data/huggingface.csv](data/huggingface.csv) by `scripts/hf_sync.py`, "
        "so edit the CSV, not this page. The note column is the only part filled in by hand.", "",
        "| Updated | Type | Hugging Face | Note | Version |",
        "| --- | --- | --- | --- | --- |",
    ]
    for r in rows:
        notes = ", ".join(f"[{n.split('/')[-1].removesuffix('.md')}]({n})" for n in r["note"].split(";") if n.strip()) or "needs a note"
        name = f"[{r['repo']}]({hf_url(r)})" + (" (no longer public)" if r["status"] == "gone" else "")
        lines.append(f"| {r['updated']} | {r['type']} | {name} | {notes} | [{r['revision'][:8]}]({hf_url(r, r['revision'])}) |")
    with open(MD_PATH, "w") as f:
        f.write("\n".join(lines) + "\n")

def main():
    summary_path = sys.argv[sys.argv.index("--summary") + 1] if "--summary" in sys.argv else None
    rows = load_rows()
    seen, changes = set(), []
    for kind, plural in KINDS.items():
        for info in get(f"https://huggingface.co/api/{plural}?author={HF_USER}&limit=1000&full=true"):
            if info.get("private"): continue  # never write private repo names into this public repo
            key = (kind, info["id"])
            seen.add(key)
            old = rows.get(key)
            new = {"type": kind, "repo": info["id"], "revision": info["sha"],
                   "updated": info["lastModified"][:10], "status": "public", "note": old["note"] if old else ""}
            if old is None:
                changes.append(f"- New {kind}: [{info['id']}]({hf_url(new)}). It needs a note in data/huggingface.csv.")
            elif old["revision"] != new["revision"] or old["status"] != "public":
                titles = commits_since(kind, info["id"], old["revision"])
                changes.append(f"- Updated {kind}: [{info['id']}]({hf_url(new)}) {old['revision'][:8]} → {new['revision'][:8]}"
                               + "".join(f"\n  - {t}" for t in titles))
            rows[key] = new
    for key, r in rows.items():
        if key not in seen and r["status"] != "gone":
            r["status"] = "gone"
            changes.append(f"- {r['type'].capitalize()} {r['repo']} is no longer public on Hugging Face. Its last pinned version is kept.")
    ordered = sorted(rows.values(), key=lambda r: (r["updated"], r["repo"]), reverse=True)
    with open(CSV_PATH, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader(); w.writerows(ordered)
    write_md(ordered)
    report = "Hugging Face changed since the last sync:\n\n" + "\n".join(changes) if changes else "Nothing changed on Hugging Face."
    print(report)
    if summary_path:
        with open(summary_path, "w") as f:
            f.write(report + "\n\nGenerated by `scripts/hf_sync.py`. Merge this to record the new versions.\n")

if __name__ == "__main__":
    main()
